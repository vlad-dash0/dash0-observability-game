// Builds hub/globe-data.mjs: land dots for the hub globe, sampled from Natural Earth
// 1:110m admin-0 countries (public domain). Node only, no dependencies.
//
//   node tools/build-globe-data.mjs [--file <local copy of the pinned file>] [--out <path>]
//
// Fetches the pinned file (or reads --file), REFUSES unless its SHA-256 equals SOURCE_SHA256,
// lays an N-point Fibonacci lattice on the sphere, keeps the points that fall on land (first
// matching polygon in file order, holes respected, Antarctica skipped) and writes them as
// lattice indices plus a country table. Output is deterministic: same file, same bytes.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { latticePoint } from '../lib/globe-lattice.mjs';

export const SOURCE_VERSION = 'v5.1.2';
export const SOURCE_URL = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${SOURCE_VERSION}/geojson/ne_110m_admin_0_countries.geojson`;
export const SOURCE_SHA256 = '6866c877d39cba9c357620878839b336d569f8c662d3cfab4cb1dbe2d39c977f';
export const LATTICE_POINTS = 26000;
const SKIP = new Set(['ATA']); // Antarctica

/** Throws unless the bytes hash to `expected`. */
export function verifyHash(bytes, expected = SOURCE_SHA256) {
  const got = createHash('sha256').update(bytes).digest('hex');
  if (got !== expected) throw new Error(`refusing: source SHA-256 ${got} does not match the pinned ${expected}`);
}

export const OVERSEAS_DEG = 60;

/** Great-circle distance in degrees between two [lon, lat] points. */
export function arcDegrees([x0, y0], [x1, y1]) {
  const r = Math.PI / 180;
  const c = Math.sin(y0 * r) * Math.sin(y1 * r) + Math.cos(y0 * r) * Math.cos(y1 * r) * Math.cos((x0 - x1) * r);
  return Math.acos(Math.max(-1, Math.min(1, c))) / r;
}

// Ray casting; ring is [[lon, lat], ...].
function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/**
 * → { countries: [[iso3, subregion], ...] sorted by iso3, dots: [[latticeIndex, countryIndex], ...]
 * ascending } for a parsed GeoJSON FeatureCollection. The country code is `ADM0_A3`, not
 * `ISO_A3`: Natural Earth leaves ISO_A3 at -99 for France and Norway.
 */
export function sampleDots(geojson, n = LATTICE_POINTS) {
  const byIso = new Map();
  const polys = [];
  for (const f of geojson.features) {
    const { ADM0_A3: iso, SUBREGION: sub } = f.properties;
    if (SKIP.has(iso)) continue;
    byIso.set(iso, sub);
    const all = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
    const parts = all.map((rings) => {
      const xs = rings[0].map((p) => p[0]);
      const ys = rings[0].map((p) => p[1]);
      const box = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
      return { iso, rings, box, centre: [(box[0] + box[2]) / 2, (box[1] + box[3]) / 2], area: (box[2] - box[0]) * (box[3] - box[1]) };
    });
    // Overseas rule: a part whose bounding-box centre is more than OVERSEAS_DEG of arc from the
    // centre of the country's largest part is an overseas territory and is dropped, so a country
    // never lights a far-away region. In the pinned file this drops only French Guiana (64 deg
    // from France); Svalbard (14), the Canaries (n/a at 110m), Alaska (41 to 50) and Hawaii (54
    // to 56) stay.
    const main = parts.reduce((a, b) => (b.area > a.area ? b : a));
    for (const p of parts) if (arcDegrees(main.centre, p.centre) <= OVERSEAS_DEG) polys.push(p);
  }
  const countries = [...byIso].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  const index = new Map(countries.map(([iso], i) => [iso, i]));
  const dots = [];
  for (let i = 0; i < n; i++) {
    const [lat, lon] = latticePoint(i, n);
    for (const p of polys) {
      const [x0, y0, x1, y1] = p.box;
      if (lon < x0 || lon > x1 || lat < y0 || lat > y1) continue;
      if (inRing(lon, lat, p.rings[0]) && !p.rings.slice(1).some((h) => inRing(lon, lat, h))) {
        dots.push([i, index.get(p.iso)]);
        break;
      }
    }
  }
  return { countries, dots };
}

/** The source of hub/globe-data.mjs for `sampleDots` output. */
export function renderModule({ countries, dots }, n = LATTICE_POINTS) {
  const buf = Buffer.alloc(dots.length * 3);
  dots.forEach(([i, c], k) => {
    if (!Number.isInteger(i) || i < 0 || i > 0xffff) throw new Error(`lattice index ${i} does not fit in a u16`);
    if (!Number.isInteger(c) || c < 0 || c > 0xff) throw new Error(`country index ${c} does not fit in a u8`);
    buf.writeUInt16LE(i, k * 3);
    buf.writeUInt8(c, k * 3 + 2);
  });
  const b64 = buf.toString('base64');
  const chunks = b64.match(/.{1,100}/g).map((s) => `  '${s}'`);
  return `// GENERATED by tools/build-globe-data.mjs. Do not edit by hand.
// Source: Natural Earth 1:110m admin-0 countries (public domain), ${SOURCE_VERSION}
//   ${SOURCE_URL}
//   SHA-256 ${SOURCE_SHA256}
// Regenerate: node tools/build-globe-data.mjs   (refuses if the download hash differs)
// ${dots.length} land dots from a ${n}-point Fibonacci lattice; Antarctica and overseas parts (over ${OVERSEAS_DEG} deg from a country's main landmass: French Guiana) left out.
// A dot is stored as its lattice index (u16) and a COUNTRIES index (u8), base64, 3 bytes each.
import { latticePoint } from '../lib/globe-lattice.mjs';

export const LATTICE_POINTS = ${n};
// [ADM0_A3, SUBREGION], sorted by code. ADM0_A3 stands in for ISO_A3, which is -99 for France and Norway.
export const COUNTRIES = [
${countries.map((c) => `  ${JSON.stringify(c)},`).join('\n')}
];
const PACKED =
${chunks.join(' +\n')};

const bytes = Uint8Array.from(atob(PACKED), (ch) => ch.charCodeAt(0));
/** [[lat, lon, iso3, subregion], ...] in lattice order. */
export const DOTS = Object.freeze(
  Array.from({ length: bytes.length / 3 }, (_, k) => {
    const [lat, lon] = latticePoint(bytes[k * 3] | (bytes[k * 3 + 1] << 8), LATTICE_POINTS);
    const [iso, sub] = COUNTRIES[bytes[k * 3 + 2]];
    return Object.freeze([lat, lon, iso, sub]);
  }),
);
`;
}

async function main(argv) {
  const opt = (name) => {
    const i = argv.indexOf(name);
    return i === -1 ? null : argv[i + 1];
  };
  const out = opt('--out') ?? fileURLToPath(new URL('../hub/globe-data.mjs', import.meta.url));
  const file = opt('--file');
  let bytes;
  if (file) bytes = readFileSync(file);
  else {
    const res = await fetch(SOURCE_URL);
    if (!res.ok) throw new Error(`fetch ${SOURCE_URL}: HTTP ${res.status}`);
    bytes = Buffer.from(await res.arrayBuffer());
  }
  verifyHash(bytes);
  writeFileSync(out, renderModule(sampleDots(JSON.parse(bytes.toString('utf8')))));
  console.log(`wrote ${out}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2)).catch((e) => {
    console.error(e.message);
    process.exit(1);
  });
}
